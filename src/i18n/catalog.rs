#[derive(Clone, Copy)]
struct Entry {
    en: &'static str,
    fr: &'static str,
    de: &'static str,
}

pub fn text(language: Language, key: TextKey) -> &'static str {
    let entry = entry(key);
    match language {
        Language::English => entry.en,
        Language::French => entry.fr,
        Language::German => entry.de,
    }
}

